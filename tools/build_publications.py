"""Generate publications.qmd from data/publications.toml.

Run from the project root:  python tools/build_publications.py
Quarto runs it automatically before every render (see pre-render in _quarto.yml).
Only the Python standard library is needed (tomllib, Python 3.11+).
"""
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "publications.toml"
OUT = ROOT / "publications.qmd"

SECTIONS = [
    ("book", "Books"),
    ("article", "Journal articles"),
    ("chapter", "Chapters"),
    ("edited", "Edited volumes"),
    ("other", "Proceedings, manuals and other"),
]

# Bold the author's own name in any of the forms used in the CV
SELF = re.compile(r"Borgatti(?:,?\s*(?:S\.\s?P\.|S\.P\.|SP|S\.|S|Steve|Stephen P\.|Stephen))?(?=[\s,.;&)]|$)")


def md_escape(text: str) -> str:
    """Escape characters that Pandoc markdown would otherwise interpret."""
    text = text.replace("\\", "\\\\")
    for ch in "*_[]<>`$@#|~^":
        text = text.replace(ch, "\\" + ch)
    return text


def render_citation(c: str) -> str:
    c = md_escape(c)
    # SELF matches the escaped text too: names never contain escaped characters
    return SELF.sub(lambda m: f"**{m.group(0)}**", c)


def links(p: dict) -> str:
    out = []
    if p.get("pdf"):
        if not (ROOT / "papers" / p["pdf"]).exists():
            raise SystemExit(f"publications.toml: papers/{p['pdf']} does not exist")
        out.append(f"[PDF](papers/{p['pdf']}){{.pub-link}}")
    if p.get("doi"):
        out.append(f"[DOI](https://doi.org/{p['doi']}){{.pub-link}}")
    if p.get("url"):
        out.append(f"[Link]({p['url']}){{.pub-link}}")
    return (" " + " ".join(out)) if out else ""


def main() -> None:
    pubs = [p for p in tomllib.loads(DATA.read_text(encoding="utf-8"))["pub"] if not p.get("hidden")]
    n_pdf = sum(1 for p in pubs if p.get("pdf"))

    lines = [
        "---",
        "title: Publications",
        "toc: true",
        "toc-title: Sections",
        "# GENERATED by tools/build_publications.py from data/publications.toml. Edit that file, not this one.",
        "---",
        "",
        f"{len(pubs)} publications, {n_pdf} with a downloadable PDF. "
        "For citation counts, see my [Google Scholar profile](https://scholar.google.com/citations?user=hlk4a4gAAAAJ&hl=en).",
        "",
        '```{=html}',
        '<div class="pub-filter-wrap">',
        '  <input id="pub-filter" type="search" placeholder="Filter by title, co-author, journal or year…" aria-label="Filter publications">',
        '  <span id="pub-count" aria-live="polite"></span>',
        "</div>",
        "```",
        "",
    ]
    for key, heading in SECTIONS:
        items = [p for p in pubs if p["type"] == key]
        if not items:
            continue
        lines += [f"## {heading} {{#{key}s}}", "", "::: {.pub-list}", ""]
        for p in items:
            lines.append(f"- {render_citation(p['citation'])}{links(p)}")
        lines += ["", ":::", ""]

    lines += [
        "```{=html}",
        "<script>",
        "(() => {",
        "  const box = document.getElementById('pub-filter');",
        "  const count = document.getElementById('pub-count');",
        "  const items = [...document.querySelectorAll('.pub-list li')];",
        "  const sections = [...document.querySelectorAll('section.level2')];",
        "  const run = () => {",
        "    const terms = box.value.toLowerCase().split(/\\s+/).filter(Boolean);",
        "    let shown = 0;",
        "    items.forEach(li => {",
        "      const t = li.textContent.toLowerCase();",
        "      const ok = terms.every(w => t.includes(w));",
        "      li.hidden = !ok; if (ok) shown++;",
        "    });",
        "    sections.forEach(s => { s.hidden = terms.length > 0 && !s.querySelector('.pub-list li:not([hidden])'); });",
        "    count.textContent = terms.length ? `${shown} of ${items.length}` : '';",
        "  };",
        "  box.addEventListener('input', run);",
        "})();",
        "</script>",
        "```",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"publications.qmd: {len(pubs)} entries, {n_pdf} PDFs")


if __name__ == "__main__":
    main()
